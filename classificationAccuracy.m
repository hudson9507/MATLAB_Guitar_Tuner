clear;
clc;

%define guitar strings and tuning conditions
notes = ["E2", "A2", "D3", "G3", "B3", "E4"];
folders = ["FlatTuning", ...
           "SlightFlatTuning", ...
           "StandardTuning", ...
           "SlightSharpTuning", ...
           "SharpTuning"];
conditions = ["Flat", ...
              "Slightly Flat", ...
              "Standard", ...
              "Slightly Sharp", ...
              "Sharp"];
expectedStatus = ["Flat", ...
                  "Flat", ...
                  "In Tune", ...
                  "Sharp", ...
                  "Sharp"];
rootFolder = fullfile(fileparts(mfilename('fullpath')), ...
                      'GuitarNotes');

%initialize counters
totalTests = zeros(1, 5);
correctTuning = zeros(1, 5);
correctNote = zeros(1, 5);
correctBoth = zeros(1, 5);

%analyze each recording
for i = 1:length(notes)
    for j = 1:length(folders)
        folderPath = fullfile(rootFolder, folders(j));
        files = dir(fullfile(folderPath, ...
                    notes(i) + "_*.wav"));
        if isempty(files)
            warning("Missing recording: %s in %s", ...
                    notes(i), folders(j));
            continue;
        end
        for k = 1:length(files)
            %import audio
            filePath = fullfile(files(k).folder, ...
                               files(k).name);
            [audio, Fs] = audioread(filePath);
            %estimate fundamental frequency
            detectedFreq = measurePitch(audio, Fs);
            %automatically identify note and tuning status
            [note, cents, status] = ...
                checkTuning(detectedFreq);
            %compare predictions against expected values
            tuningMatch = status == expectedStatus(j);
            noteMatch = note == notes(i);
            %update counters
            totalTests(j) = totalTests(j) + 1;
            correctTuning(j) = correctTuning(j) ...
                               + tuningMatch;
            correctNote(j) = correctNote(j) ...
                             + noteMatch;
            correctBoth(j) = correctBoth(j) ...
                             + (tuningMatch && noteMatch);
            %print individual results
            fprintf(['Expected: %s | Detected: %s | ' ...
                     'Frequency: %.2f Hz | ' ...
                     'Cents: %+.2f | ' ...
                     'Expected Status: %s | ' ...
                     'Detected Status: %s\n'], ...
                     notes(i), note, detectedFreq, cents, ...
                     expectedStatus(j), status);
        end
    end
end

%calculate classification accuracy
tuningAccuracy = 100 * correctTuning ./ totalTests;
noteAccuracy = 100 * correctNote ./ totalTests;
combinedAccuracy = 100 * correctBoth ./ totalTests;

%create results table
results = table(conditions', ...
                totalTests', ...
                correctTuning', ...
                correctNote', ...
                correctBoth', ...
                tuningAccuracy', ...
                noteAccuracy', ...
                combinedAccuracy', ...
    'VariableNames', {'Condition', ...
                      'TotalTests', ...
                      'CorrectTuning', ...
                      'CorrectNote', ...
                      'CorrectBoth', ...
                      'TuningAccuracy', ...
                      'NoteAccuracy', ...
                      'CombinedAccuracy'});
disp(results);

%print overall accuracy
fprintf('\nTotal Recordings Tested: %d\n', ...
        sum(totalTests));
fprintf('Overall Tuning Accuracy: %.2f%%\n', ...
        100 * sum(correctTuning) / sum(totalTests));
fprintf('Overall Note Identification Accuracy: %.2f%%\n', ...
        100 * sum(correctNote) / sum(totalTests));
fprintf('Overall Combined Accuracy: %.2f%%\n', ...
        100 * sum(correctBoth) / sum(totalTests));

%export results
writetable(results, 'ClassificationAccuracy.csv');

%generate classification accuracy graph
%combine accuracy measurements into a matrix
accuracyData = [tuningAccuracy', ...
    noteAccuracy', ...
    combinedAccuracy'];

%create grouped bar graph
figure('Color', 'w');
bar(accuracyData, 'grouped');

%configure axes
set(gca, 'XTick', 1:length(conditions), ...
    'XTickLabel', conditions, ...
    'FontSize', 12);
title('Guitar Tuner Classification Accuracy');
xlabel('Tuning Condition');
ylabel('Classification Accuracy (%)');

%configure axis limits
ylim([0 110]);
yticks(0:20:100);

%add reference line for perfect accuracy
yline(100, 'k--', '100% Accuracy', ...
    'HandleVisibility', 'off');

%add legend
lgd = legend('Tuning Accuracy', ...
    'Note Identification Accuracy', ...
    'Combined Accuracy', ...
    'Location', 'bestoutside');
grid on;
box on;

%set background and text colors
ax = gca;
ax.Color = 'white';
ax.XColor = 'black';
ax.YColor = 'black';
ax.Title.Color = 'black';
ax.XLabel.Color = 'black';
ax.YLabel.Color = 'black';
ax.GridColor = [0.5 0.5 0.5];

%set legend colors
lgd.TextColor = 'black';
lgd.Color = 'white';
lgd.EdgeColor = 'black';

%export graph for report
exportgraphics(gcf, 'ClassificationAccuracy.png', ...
    'Resolution', 300);